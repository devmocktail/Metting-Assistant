<?php
// Build a single self-contained index.php (all classes + inline admin page) so
// it can be deployed by uploading flat files — no folders, no zip extraction.
// Output goes to dist/.
$root = __DIR__;
$dist = $root . '/dist';
@mkdir($dist, 0775, true);

function stripOpen(string $php): string
{
    // Remove a leading open tag (and an optional closing tag at EOF).
    $open = '<' . '?php';
    $close = '?' . '>';
    $php = preg_replace('/^\xEF\xBB\xBF/', '', $php); // strip BOM if any
    $php = preg_replace('/^\s*' . preg_quote($open, '/') . '\s*/', '', $php, 1);
    $php = preg_replace('/' . preg_quote($close, '/') . '\s*$/', '', $php);
    return trim($php) . "\n";
}

// 1) Classes, in dependency order (Http/HttpException first).
$classFiles = ['app/Http.php', 'app/Config.php', 'app/Tokens.php', 'app/Store.php', 'app/Google.php', 'app/Razorpay.php', 'app/Users.php'];
$classes = '';
foreach ($classFiles as $f) {
    $classes .= "\n// ===== {$f} =====\n" . stripOpen(file_get_contents("$root/$f")) . "\n";
}
// In the single file, config.php and data/ sit next to index.php (not one level up).
$classes = str_replace("__DIR__ . '/../config.php'", "__DIR__ . '/config.php'", $classes);
$classes = str_replace("__DIR__ . '/../data/app.sqlite'", "__DIR__ . '/data/app.sqlite'", $classes);

// 2) Inline admin page: admin.js folded into admin/index.html, API base absolute.
$adminJs = file_get_contents("$root/admin/admin.js");
$adminJs = str_replace(
    "const API_BASE = new URL('api/', location.href).href;",
    "const API_BASE = '/admin/api/';",
    $adminJs
);
$adminHtml = file_get_contents("$root/admin/index.html");
$adminHtml = str_replace('<script src="admin.js"></script>', "<script>\n$adminJs\n</script>", $adminHtml);
$adminConst = "const ADMIN_HTML = " . var_export($adminHtml, true) . ";\n";

// Inline the marketing landing page (served at "/") if it exists.
$landingPath = $root . '/../website/index.html';
$landingConst = is_file($landingPath)
    ? "const LANDING_HTML = " . var_export(file_get_contents($landingPath), true) . ";\n"
    : '';

// 3) Routing from index.php (open tag and require lines stripped); add /admin page route.
$routing = stripOpen(file_get_contents("$root/index.php"));
$routing = preg_replace('/^\s*require __DIR__.*$/m', '', $routing);
$adminRoute = <<<'PHP'
    if ($method === 'GET' && ($path === '/admin' || $path === '/admin/')) {
        header('Content-Type: text/html; charset=utf-8');
        echo ADMIN_HTML;
        exit;
    }

PHP;
$needle = "    if (strpos(\$path, '/admin/api') === 0) {";
$routing = str_replace($needle, $adminRoute . $needle, $routing);

// 4) Assemble.
$out = "<?php\n"
    . "// Single-file build of the Meeting Assistant PHP backend. Generated by build-single.php.\n"
    . "// Deploy: upload this index.php + config.php + .htaccess into public_html (no folders).\n"
    . $classes
    . "\n$adminConst\n$landingConst\n"
    . $routing;
file_put_contents("$dist/index.php", $out);

// 5) .htaccess for the flat deploy (route everything to index.php; protect config.php).
$htaccess = <<<'HT'
CGIPassAuth On
<IfModule mod_rewrite.c>
  RewriteEngine On
  RewriteCond %{HTTP:Authorization} ^(.+)$
  RewriteRule ^ - [E=HTTP_AUTHORIZATION:%1]
  RewriteRule ^config\.php$ - [F,L]
  RewriteCond %{REQUEST_FILENAME} -f [OR]
  RewriteCond %{REQUEST_FILENAME} -d
  RewriteRule ^ - [L]
  RewriteRule ^ index.php [L]
</IfModule>
<FilesMatch "^config\.php$">
  Require all denied
</FilesMatch>
HT;
file_put_contents("$dist/.htaccess", $htaccess);
copy("$root/config.php.example", "$dist/config.php.example");

echo "Built dist/index.php (" . round(filesize("$dist/index.php") / 1024, 1) . " KB)\n";
echo "Built dist/.htaccess\n";
